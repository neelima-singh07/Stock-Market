load_dotenv()
st.set_page_config(page_title="AlphaShock", page_icon="📉", layout="wide")

ANOMALY_TRACE = 3  # index of the anomaly marker trace in the figure
MODE_LABELS = {
    "hybrid_rerank": "Time-filtered hybrid + rerank (full)",
    "hybrid": "Time-filtered hybrid (no rerank)",
    "time_dense": "Time-filtered dense only",
    "naive": "Naive vector search (baseline)",
}


# ----------------------------------------------------------------------- cached resources
@st.cache_resource(show_spinner="Indexing documents in Qdrant (first run downloads models)...")
def get_retriever(documents_json: str) -> HybridRetriever:
    documents = TypeAdapter(list[Document]).validate_json(documents_json)
    return HybridRetriever(documents)


@st.cache_data(show_spinner="Fitting Prophet and scanning for anomalies...")
def run_detection(ticker: str, z_thr: float, vol_z_thr: float, use_prophet: bool) -> tuple[pd.DataFrame, list[dict]]:
    cfg = DetectorConfig(z_threshold=z_thr, vol_z_threshold=vol_z_thr, use_prophet=use_prophet)
    res = AnomalyDetector(cfg).analyze(load_prices(ticker), ticker)
    return res.frame, [e.model_dump(mode="json") for e in res.events]


def build_figure(frame: pd.DataFrame, events: list[AnomalyEvent], selected_id: str | None, ticker: str) -> go.Figure:
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=frame["date"], y=frame["price_upper"], line=dict(width=0),
                             hoverinfo="skip", showlegend=False))                                   # 0
    fig.add_trace(go.Scatter(x=frame["date"], y=frame["price_lower"], line=dict(width=0), fill="tonexty",
                             fillcolor="rgba(99,110,250,0.18)", name="Expected band", hoverinfo="skip"))  # 1
    fig.add_trace(go.Candlestick(x=frame["date"], open=frame["open"], high=frame["high"], low=frame["low"],
                                 close=frame["close"], name=ticker))                                 # 2
    highs = frame.set_index("date")["high"]
    xs = [pd.Timestamp(e.timestamp).tz_localize(None).normalize() for e in events]
    ys = [float(highs.get(x, float("nan"))) * 1.02 for x in xs]
    fig.add_trace(go.Scatter(                                                                        # 3
        x=xs, y=ys, mode="markers", name="Anomaly", customdata=[e.event_id for e in events],
        marker=dict(color="red", size=[16 if e.event_id == selected_id else 9 for e in events],
                    line=dict(color="white", width=[2 if e.event_id == selected_id else 0 for e in events])),
        hovertemplate="%{customdata}<extra>click for root cause</extra>"))
    fig.update_layout(height=520, xaxis_rangeslider_visible=False, margin=dict(l=10, r=10, t=30, b=10),
                      legend=dict(orientation="h"), clickmode="event+select")
    return fig


def chunks_table(res: RetrievalResult, which: str = "candidates") -> pd.DataFrame:
    rows = []
    for c in getattr(res, which):
        rows.append({
            "rank": c.final_rank or None, "doc_id": c.doc.doc_id, "source": c.doc.source,
            "published (UTC)": f"{c.doc.published_at:%Y-%m-%d %H:%M}", "title": c.doc.title,
            "dense": c.dense_score, "dense_rank": c.dense_rank, "bm25": c.bm25_score, "bm25_rank": c.bm25_rank,
            "rrf": c.rrf_score, "rerank": c.rerank_score,
            "true catalyst": c.doc.is_catalyst and c.doc.event_id == res.event_id,
        })
    return pd.DataFrame(rows)


def render_report(rep: RCAReport) -> None:
    st.markdown(f"**Primary catalyst:** {rep.primary_catalyst}")
    c1, c2, c3 = st.columns(3)
    c1.metric("Category", rep.catalyst_category.value)
    c2.metric("Confidence", rep.confidence.value)
    c3.caption(f"Generated by `{rep.generated_by}`")
    st.write(rep.summary)
    if rep.findings:
        st.markdown("**Cited findings**")
        for f in rep.findings:
            st.markdown(f"- {f.claim}  " + " ".join(f"`[{c}]`" for c in f.citations))
    if rep.market_impact:
        st.markdown(f"**Market impact:** {rep.market_impact}")
    for cav in rep.caveats:
        st.caption(f"⚠️ {cav}")


# ----------------------------------------------------------------------- page
st.title("📉 AlphaShock: volatility & SEC filing surveillance")

if not data_ready():
    st.warning(
        "The data corpus is missing or does not overlap the available price history. "
        "Bootstrap the aligned corpus before running retrieval."
    )
    if st.button("Bootstrap data now", type="primary"):
        with st.spinner("Downloading prices and generating the document corpus..."):
            bootstrap()
        st.rerun()
    st.stop()

# apply a chart click before the selectbox is instantiated
if "pending_event" in st.session_state:
    st.session_state["event_select"] = st.session_state.pop("pending_event")

with st.sidebar:
    ticker = st.selectbox("Ticker", TICKERS)
    z_thr = st.slider("Return Z threshold (sigma)", 2.0, 5.0, 3.0, 0.5)
    vol_z_thr = st.slider("Volume Z threshold", 2.0, 6.0, 3.0, 0.5)
    use_prophet = st.toggle("Use Prophet (off = rolling Z-score only)", value=True)
    mode = st.radio("Retrieval mode", list(MODE_LABELS), format_func=MODE_LABELS.get)
    provider = st.selectbox("LLM provider", ["auto", "gemini", "litellm", "offline"])
    fetch_live = st.toggle("Fetch fresh news + SEC filings", value=True)

frame, event_dicts = run_detection(ticker, z_thr, vol_z_thr, use_prophet)
events = [AnomalyEvent.model_validate(d) for d in event_dicts]
# Prefer anomalies represented in the local evidence corpus so the default
# selection demonstrates the end-to-end root-cause workflow.
evidence_event_ids = {d.event_id for d in load_documents() if d.event_id}
events.sort(key=lambda e: (e.event_id not in evidence_event_ids, e.timestamp))
by_id = {e.event_id: e for e in events}

if not events:
    st.info("No anomalies at these thresholds.")
    st.stop()

default_event_id = events[0].event_id
if st.session_state.get("event_select_ticker") != ticker:
    st.session_state["event_select"] = default_event_id
    st.session_state["event_select_ticker"] = ticker
elif st.session_state.get("event_select") not in by_id:
    st.session_state["event_select"] = default_event_id
with st.sidebar:
    selected_id = st.selectbox(
        "Anomaly", list(by_id), key="event_select",
        format_func=lambda i: f"{i}  ({by_id[i].pct_change:+.1f}%, z={by_id[i].z_score:+.1f})")

fig = build_figure(frame, events, selected_id, ticker)
sel = st.plotly_chart(fig, use_container_width=True, key=f"chart_{ticker}", on_select="rerun",
                      selection_mode="points")
points = (sel or {}).get("selection", {}).get("points", []) if sel else []
for p in points:
    if p.get("curve_number") == ANOMALY_TRACE:
        i = p.get("point_index", p.get("point_number"))
        if i is not None and 0 <= i < len(events):
            clicked = events[i].event_id
            if st.session_state.get("last_click") != (ticker, clicked):
                st.session_state["last_click"] = (ticker, clicked)
                if clicked != selected_id:
                    st.session_state["pending_event"] = clicked
                    st.rerun()
        break

event = by_id[selected_id]
st.subheader(f"{event.ticker} · {event.timestamp:%Y-%m-%d}")
m1, m2, m3, m4, m5 = st.columns(5)
m1.metric("Price change", f"{event.pct_change:+.2f}%")
m2.metric("Return z-score", f"{event.z_score:+.2f}")
m3.metric(
    "Volume vs 20d median",
    f"{event.volume_spike_ratio:.2f}x" if event.volume_spike_ratio > 0 else "N/A",
)
m4.metric("Trigger", event.trigger)
m5.metric("Detector", event.method)

local_documents = load_documents()
search_documents = local_documents
live_errors: list[str] = []
if fetch_live:
    with st.spinner("Fetching fresh news and SEC filings for this anomaly..."):
        fresh_documents, live_errors = fetch_fresh_documents(
            event.ticker, event.timestamp - pd.Timedelta(hours=48),
            event.timestamp + pd.Timedelta(hours=12),
        )
    if fresh_documents:
        by_doc_id = {document.doc_id: document for document in local_documents}
        by_doc_id.update({document.doc_id: document for document in fresh_documents})
        search_documents = list(by_doc_id.values())
        st.caption(f"Live ingestion added {len(fresh_documents)} fresh document(s) to the local corpus.")
    elif live_errors:
        st.warning("Live ingestion returned no documents; using the local corpus.")
for error in live_errors:
    st.caption(f"Live source detail: {error}")

documents_json = TypeAdapter(list[Document]).dump_json(search_documents).decode("utf-8")
retriever = get_retriever(documents_json)
result = retriever.retrieve(event, mode=mode)  # type: ignore[arg-type]

cache = st.session_state.setdefault("reports", {})
key = (event.event_id, mode, provider)
if key not in cache:
    with st.spinner("Synthesizing root-cause report..."):
        cache[key] = CatalystSynthesizer(provider=provider).generate(event, result.top)  # type: ignore[arg-type]

left, right = st.columns([3, 2])
with left:
    st.markdown("### Root-cause report")
    render_report(cache[key])
with right:
    st.markdown("### Retrieval debug")
    if result.window_start:
        st.caption(f"Window {result.window_start:%Y-%m-%d %H:%M} to {result.window_end:%Y-%m-%d %H:%M} UTC · "
                   f"{result.n_filtered} docs pass the ticker+time filter")
        if not result.top:
            st.warning(
                "No matching evidence exists in the local corpus for this anomaly. "
                "The report is marked Unexplained rather than guessing a catalyst. "
                "Select an anomaly with indexed evidence or rebuild the corpus with additional documents."
            )
    else:
        st.caption("No metadata filter applied (naive baseline).")
    st.caption(f"Dense query: {result.dense_query}")
    st.caption(f"BM25 query: {result.sparse_query}")

st.markdown("#### Final top-5 (sent to the LLM)")
st.dataframe(chunks_table(result, "top"), use_container_width=True, hide_index=True)
with st.expander("Stage-1 candidates (top 20 after RRF) with all scores"):
    st.dataframe(chunks_table(result, "candidates"), use_container_width=True, hide_index=True)
with st.expander("Naive vector search baseline for comparison"):
    naive = retriever.retrieve(event, mode="naive")
    st.dataframe(chunks_table(naive, "top"), use_container_width=True, hide_index=True)
