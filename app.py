from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from dotenv import load_dotenv
from pydantic import TypeAdapter

from src.anomaly.detector import AnomalyDetector, AnomalyEvent, DetectorConfig
from src.config import TICKERS
from src.data.bootstrap_data import bootstrap
from src.data.live_ingest import fetch_fresh_documents
from src.data.loaders import data_ready, load_documents, load_prices
